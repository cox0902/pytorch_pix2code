class TokenEmbedding(nn.Module):
    def __init__(self, vocab_size, emb_size):
        super(TokenEmbedding, self).__init__()
        self.embedding = nn.Embedding(vocab_size, emb_size) 
        self.emb_size = emb_size

    def forward(self, tokens):
        return self.embedding(tokens.long()) * math.sqrt(self.emb_size)


class PositionalEncoding(nn.Module):
    def __init__(self,
                 emb_size: int,
                 dropout: float = 0.1,
                 maxlen: int = 5000):
        super(PositionalEncoding, self).__init__()
        
        den = torch.exp(- torch.arange(0, emb_size, 2)* math.log(10000) / emb_size)
        pos = torch.arange(0, maxlen).reshape(maxlen, 1)
        pos_embedding = torch.zeros((maxlen, emb_size))
        pos_embedding[:, 0::2] = torch.sin(pos * den)
        pos_embedding[:, 1::2] = torch.cos(pos * den)
        pos_embedding = pos_embedding.unsqueeze(-2)

        self.dropout = nn.Dropout(dropout)
        self.register_buffer('pos_embedding', pos_embedding)

    def forward(self, token_embedding):
        # return self.dropout(token_embedding + self.pos_embedding[:token_embedding.size(0), :])
        return self.pos_embedding[:token_embedding.size(0), :]


class Ui2Box(nn.Module):

    def __init__(self,
                 vocab_size,
                 max_len,
                 proof_of_concept=False,
                 kl_loss=None,
                 loss="giou"):
        super().__init__()

        self.loss = loss
        self.kl_loss = (kl_loss == "1")

        print({
            "loss": self.loss,
            "kl_loss": self.kl_loss,
        })

        self.backbone = build_backbone("resnet50")
        self.transformer = Transformer()
        hidden_dim = self.transformer.d_model
        self.bbox_embed = MLP(hidden_dim, hidden_dim, 4, 3)
        self.token_embed = TokenEmbedding(vocab_size, hidden_dim)
        self.query_embed = PositionalEncoding(hidden_dim)
        self.input_proj = nn.Conv2d(self.backbone.num_channels, hidden_dim, kernel_size=1)

        if self.loss == "giou":
            self.criterion = torchvision.ops.generalized_box_iou_loss
        elif self.loss == "diou":
            self.criterion = torchvision.ops.distance_box_iou_loss
        elif self.loss == "ciou":
            self.criterion = torchvision.ops.complete_box_iou_loss
        elif self.loss == "kl" or self.loss == "w2":
            self.criterion = None
        else:
            assert False

        if self.kl_loss:
            self.log_vars = nn.Parameter(torch.zeros((2, ), requires_grad=True))
        
    def forward(self, batch):
        image = batch["image"]
        code = batch["code"].long()
        code_len = batch["code_len"]
        truth_box = batch["rect"]

        # print("code:", code.shape)

        features, pos = self.backbone(image)
        src = features[-1]
        tgt = self.token_embed(code)
        query = self.query_embed(tgt)
        hs = self.transformer(self.input_proj(src), tgt, code == 0, query, pos[-1])[0] 

        # print("hs:", hs.shape)

        preds_box = self.bbox_embed(hs).sigmoid()
        preds_box = preds_box[0]

        # print("preds_box:", preds_box.shape)

        #

        decode_lengths = code_len.cpu()
        preds_box = nn.utils.rnn.pack_padded_sequence(
            preds_box, decode_lengths, batch_first=True, enforce_sorted=False).data
        truth_box = nn.utils.rnn.pack_padded_sequence(
            truth_box, decode_lengths, batch_first=True, enforce_sorted=False).data
        truth_lbl = nn.utils.rnn.pack_padded_sequence(
            code, decode_lengths, batch_first=True, enforce_sorted=False).data
        
        box_masks = (truth_lbl > 7)

        preds_box = preds_box[box_masks]
        truth_box = truth_box[box_masks]

        # print(preds_box.shape, truth_box.shape)

        preds_box_convert = torchvision.ops.box_convert(preds_box, "cxcywh", "xyxy")
        truth_box_convert = torchvision.ops.box_convert(truth_box, "cxcywh", "xyxy")

        loss_fn = getattr(self, "loss", "giou")
        if loss_fn == "kl":
            loss = compute_kl_loss(truth_box[:, :2], torch.log((truth_box[:, 2:] / 2.0)), 
                                   preds_box[:, :2], torch.log((preds_box[:, 2:] / 2.0)))
        elif loss_fn == "w2":
            loss = compute_w2_loss(preds_box, truth_box)
        else:
            loss = self.criterion(preds_box_convert, truth_box_convert, reduction="mean")

        r = {
            "loss": loss,
            "scores": preds_box_convert.detach(), 
            "targets": truth_box_convert.detach(),
            "pb": preds_box.detach(),
            "tb": truth_box.detach()
        }

        if getattr(self, "kl_loss", False):
            
            p1 = 0.5 * torch.exp(-self.log_vars[0])
            p2 = 0.5 * torch.exp(-self.log_vars[1])

            r["loss/p1"] = p1
            r["loss/p2"] = p2
            
            loss = p1 * loss + p2 * compute_kl_loss(truth_box[:, :2], torch.log((truth_box[:, 2:] / 2.0)), 
                                                    preds_box[:, :2], torch.log((preds_box[:, 2:] / 2.0)))
            loss += self.log_vars[0] + self.log_vars[1]
            
            r["loss/box"] = r["loss"]
            r["loss"] = loss

        return r